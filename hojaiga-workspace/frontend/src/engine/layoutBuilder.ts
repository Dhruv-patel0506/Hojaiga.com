// 2. The Generator Function
export function generateCompoundGrid(width = 60, height = 60): number[][] {
    // Fill the world with the empty black void first
    const grid = Array.from({ length: height }, () => Array(width).fill(TILE.VOID));

    for (const room of CompoundRooms) {
        for (let row = room.y; row < room.y + room.h; row++) {
            for (let col = room.x; col < room.x + room.w; col++) {
                
                // If it's a private office, draw walls around the perimeter
                if (room.isWalled) {
                    const isBorder = row === room.y || row === room.y + room.h - 1 || 
                                     col === room.x || col === room.x + room.w - 1;
                    
                    // Leave a gap for the door at the bottom center of the room
                    const isDoor = row === room.y + room.h - 1 && col === room.x + Math.floor(room.w / 2);

                    if (isBorder && !isDoor) {
                        grid[row][col] = TILE.WALL;
                    } else {
                        grid[row][col] = room.floorType;
                    }
                } else {
                    // It's a bullpen, just paint the floor
                    grid[row][col] = room.floorType;
                }
            }
        }
    }
    return grid;
}

