export const TILE = {
    VOID: 0,
    WALL: 9,
    FLOOR_CEO: 1,       // Carpet
    FLOOR_MANAGER: 2,   // Wood
    FLOOR_EXECUTION: 3, // Industrial Tile
    FLOOR_AGENT: 4,     // Dark Server Floor
    FLOOR_CNS: 5        // Glowing Grid
};

