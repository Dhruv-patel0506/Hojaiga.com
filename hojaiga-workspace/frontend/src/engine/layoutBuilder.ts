export function isTileBlocked(x: number, y: number, grid: number[][]): boolean {
    // 1. Check map boundaries to prevent walking off the map
    if (y < 0 || y >= grid.length || x < 0 || x >= grid[0].length) return true;
    
    // 2. Check for solid architecture (walls)
    if (grid[y][x] === TILE.WALL) return true;
    
    // 3. Check for physical furniture collisions
    return CompoundFurniture.some(prop => prop.x === x && prop.y === y);
}
